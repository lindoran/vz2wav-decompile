#!/usr/bin/env python3
"""Generates the verbose 2018AD fast-loader debug stub used by `vz2wav --fast-debug`.

Outputs (next to this script):
  fast_debug_stub.asm   generated z80asm source (assembled for ORG)
  fast_debug_stub.bin   assembled image
  fast_debug_stub.inc   C snippet: FAST_DEBUG_STUB[] and FAST_DEBUG_RELOCS[] (paste into vz2wav.c)

Relocation: the image is assembled twice (different origins); every 16-bit word that moves with the
origin is recorded as a relocation site, so vz2wav can place the stub anywhere (default RAM, video RAM,
top of memory) exactly like the production stub. Inline hex readouts are expanded here so no CALL/RET or
index-register overhead lands in the timing-critical gaps between tape bits."""
import subprocess, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
ORG = 0x7C00
ORG2 = 0x7D40            # second origin, used only to discover relocation sites
VRAM = 0x7000
K_SYNC = 4   # counts pre-loaded after a readout in the sync loops (compensates readout time)
K_HDR  = 3   # ... after a header readout (before the next header byte)
K_BODY = 1   # ... per body byte (progress stores)

def at(row, col): return VRAM + 32*row + col

# ---- screen map (32 x 16 text screen, green-background convention: char | 0x40) ----
SYNC_LAST = at(1, 10)   # hex: period count of the most recent pulse pair while hunting for sync
SYNC_END  = at(2, 10)   # hex: count of the long pulse that ended sync (nominal 0x24)
HDR_T, HDR_LO, HDR_HI, HDR_LL, HDR_LH = at(3,4), at(3,7), at(3,10), at(3,13), at(3,16)
BODY_B, BODY_C = at(4, 6), at(4, 7)   # raw progress while loading, then OK
END_H, END_L = at(5, 6), at(5, 8)     # start+length
CKS_V   = at(5, 18)                   # "OK" / "BAD" (trailing checksum check, same test as production stub)
SHORT_V = at(6, 6)                    # last short pulse count seen while waiting for the sync-end pulse
THR_V   = at(6, 14)                   # data threshold actually used = (short + long) / 2
THR_RAW = at(6, 17)                   # raw stash of the threshold (hex-printed after the load)
STAGE   = at(7, 7)                    # E S H B D progress letters

def hexblk(reg, addr, tag):
    o = [f"        ; hex {reg} -> {addr:#06x} ({tag})", f"        ld   a,{reg}"]
    o += ["        rrca"]*4
    o += ["        and  0x0F", "        add  a,0x90", "        daa", "        adc  a,0x40", "        daa", "        or   0x40",
          f"        ld   (0x{addr:04X}),a", f"        ld   a,{reg}",
          "        and  0x0F", "        add  a,0x90", "        daa", "        adc  a,0x40", "        daa", "        or   0x40",
          f"        ld   (0x{addr+1:04X}),a"]
    return "\n".join(o)

def mark(ch, addr): return f"        ld   a,'{ch}'\n        ld   (0x{addr:04X}),a"
def put2(addr, a, b): return f"        ld   a,'{a}'\n        ld   (0x{addr:04X}),a\n        ld   a,'{b}'\n        ld   (0x{addr+1:04X}),a"

def build(org):
    L=[]; A=L.append
    A("; fast_debug_stub.asm - GENERATED by gen_debug_stub.py - verbose variant of the 2018AD fast-load stub")
    A("; Relocatable by vz2wav (see the generator for how relocation sites are found).")
    A(f"        org  0x{org:04X}")
    A("start:")
    A("        di")
    A("        ld   sp,0x7FFF           ; patched by vz2wav (private stack top)")
    A("        ld   iy,0x6800")
    A("        ; blank rows 0..7 (green-background blank = 0x60)")
    A(f"        ld   hl,0x{VRAM:04X}")
    A(f"        ld   de,0x{VRAM+1:04X}")
    A("        ld   bc,0x00FF")
    A("        ld   (hl),0x60")
    A("        ldir")
    for (r,c,lbl) in [(0,0,"s_title"),(1,0,"s_sync"),(2,0,"s_end"),(3,0,"s_hdr"),(4,0,"s_body"),(5,0,"s_endad"),(5,12,"s_cks"),(6,0,"s_short"),(6,10,"s_thr"),(7,0,"s_stage")]:
        A(f"        ld   hl,{lbl}")
        A(f"        ld   de,0x{at(r,c):04X}")
        A("        call puts")
    A(mark('E', STAGE))
    A("        ld   d,0x16              ; sync-phase threshold")
    A("sync_reload:")
    A("        ld   e,0x3C              ; need 60 consecutive short periods")
    A("sync1:")
    A(f"        ld   a,{K_SYNC}")
    A("s1a:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   nz,s1a")
    A("s1b:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   z,s1b")
    A("        ld   c,a")
    A(hexblk('c', SYNC_LAST, "live last period"))
    A("        ld   a,c"); A("        cp   d"); A("        jr   nc,sync_reload")
    A("        ld   b,c                 ; remember last short")
    A("        dec  e"); A("        jr   nz,sync1")
    A("sync2:")
    A(f"        ld   a,{K_SYNC}")
    A("s2a:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   nz,s2a")
    A("s2b:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   z,s2b")
    A("        ld   c,a"); A("        cp   d"); A("        jr   nc,sync_end")
    A("        ld   b,c                 ; remember last short")
    A(hexblk('c', SHORT_V, "last short"))
    A("        jr   sync2")
    A("sync_end:")
    A(hexblk('c', SYNC_END, "sync-end count"))
    A("        ld   a,b                 ; adaptive threshold = (short + long) / 2")
    A("        add  a,c"); A("        rra"); A("        ld   d,a")
    A(f"        ld   (0x{THR_RAW:04X}),a   ; stash raw threshold, printed after the load")
    A(mark('S', STAGE+1))
    A("        call rbh                 ; @reloc file type")
    A(hexblk('e', HDR_T, "type")); A("        ld   a,e"); A("        push af")
    A("        call rbh                 ; @reloc start lo")
    A(hexblk('e', HDR_LO, "start lo")); A("        ld   l,e")
    A("        call rbh                 ; @reloc start hi")
    A(hexblk('e', HDR_HI, "start hi")); A("        ld   h,e"); A("        push hl")
    A("        call rbh                 ; @reloc length lo")
    A(hexblk('e', HDR_LL, "len lo")); A("        ld   c,e")
    A("        call rbh                 ; @reloc length hi")
    A(hexblk('e', HDR_LH, "len hi")); A("        ld   b,e"); A("        push bc")
    A(mark('H', STAGE+2))
    A("        call rbh                 ; @reloc first body byte (follows header readout)")
    A("        jr   bstore")
    A("body:")
    A("        call rbb                 ; @reloc")
    A("bstore:")
    A("        ld   (hl),e"); A("        inc  hl"); A("        dec  bc")
    A("        ld   a,c"); A(f"        ld   (0x{BODY_C:04X}),a   ; raw progress")
    A("        ld   a,b"); A(f"        ld   (0x{BODY_B:04X}),a")
    A("        or   c"); A("        jr   nz,body")
    A("        ; ---- trailing checksum, captured exactly like the production stub (no readout in between) ----")
    A("        call rbb                 ; @reloc checksum lo")
    A("        push de")
    A("        call rb                  ; @reloc checksum hi")
    A("        push de"); A("        pop  bc"); A("        pop  de"); A("        exx")
    A(mark('B', STAGE+3))
    A("        pop  bc                  ; length")
    A("        pop  de                  ; start")
    A("        push de"); A("        ld   h,d"); A("        ld   l,e"); A("        add  hl,bc")
    A("        ld   (0x78F9),hl")
    A(hexblk('h', END_H, "end hi")); A(hexblk('l', END_L, "end lo"))
    A("        pop  hl                  ; start")
    A("        call cks                 ; @reloc  carry set = mismatch")
    A("        jr   c,ck_bad")
    A(put2(CKS_V, 'O', 'K'))
    A("        jr   ck_done")
    A("ck_bad:")
    A(put2(CKS_V, 'B', 'A')); A(mark('D', CKS_V+2))
    A("bad_halt:")
    A("        halt                     ; same as the production stub: stop on a checksum failure (panel stays visible)")
    A("        jr   bad_halt")
    A("ck_done:")
    A(f"        ld   a,(0x{THR_RAW:04X})"); A("        ld   c,a")
    A(hexblk('c', THR_V, "threshold used"))
    A("        ld   a,0x60"); A(f"        ld   (0x{THR_RAW:04X}),a")
    A(put2(BODY_B, 'O', 'K'))
    A(mark('D', STAGE+4))
    A("        ; ~2 s pause (interrupts still off) so the readout can be read; DE preserved")
    A("        push de"); A("        ld   bc,0x0000"); A("        ld   d,4")
    A("pause:  dec  bc"); A("        ld   a,b"); A("        or   c"); A("        jr   nz,pause")
    A("        dec  d"); A("        jr   nz,pause"); A("        pop  de")
    A("        pop  af                  ; type"); A("        cp   0xF1"); A("        jr   z,mc")
    A("        ld   (0x78A4),hl         ; BASIC: program start -> PRGEND pointer (as production stub)")
    A("        call 0x1AFC              ; RENEW_LINE_PTRS (DE = start)")
    A("        call 0x1B5D              ; VRESET")
    A("        ei")
    A("        ld   hl,0x79E8")
    for ch in "RUN":
        A(f"        ld   (hl),'{ch}'"); A("        inc  hl")
    A("        ld   (hl),0x00")
    A("        ld   hl,0x79E7"); A("        xor  a"); A("        jp   0x1A81")
    A("mc:     ei"); A("        jp   (hl)")
    A("; read one bit-cell into E (identical decoder to the production read_bit); rbh/rbb pre-load the count")
    A("; to compensate the time spent on readouts")
    A("rbh:    ld   e,1"); A(f"        ld   a,{K_HDR}"); A("        jr   rb2")
    A("rbb:    ld   e,1"); A(f"        ld   a,{K_BODY}"); A("        jr   rb2")
    A("rb:     ld   e,1")
    A("rb1:    xor  a")
    A("rb2:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   nz,rb2")
    A("rb3:    inc  a"); A("        bit  6,(iy+0)"); A("        jr   z,rb3")
    A("        cp   d"); A("        ccf"); A("        rl   e"); A("        jr   nc,rb1"); A("        ret")
    A("; checksum verifier: identical algorithm to the production stub (sum of start addr bytes, end addr bytes,")
    A("; payload; compares against the captured trailer in the shadow registers). In: BC=len DE=start HL=start")
    A("cks:    push bc"); A("        push de"); A("        push hl")
    A("        ld   a,e"); A("        add  a,d"); A("        ld   l,a"); A("        ld   a,0"); A("        adc  a,0"); A("        ld   h,a")
    A("cks1:   ld   a,(de)"); A("        add  a,l"); A("        ld   l,a"); A("        ld   a,h"); A("        adc  a,0"); A("        ld   h,a")
    A("        inc  de"); A("        dec  bc"); A("        ld   a,b"); A("        or   c"); A("        jr   nz,cks1")
    A("        ld   a,(0x78F9)"); A("        add  a,l"); A("        ld   l,a"); A("        ld   a,h"); A("        adc  a,0"); A("        ld   h,a")
    A("        ld   a,(0x78FA)"); A("        add  a,l"); A("        ld   l,a"); A("        ld   a,h"); A("        adc  a,0"); A("        ld   h,a")
    A("        exx"); A("        ld   a,e"); A("        exx"); A("        cp   l"); A("        jr   nz,cks_bad")
    A("        exx"); A("        ld   a,c"); A("        exx"); A("        cp   h"); A("        jr   nz,cks_bad")
    A("        pop  hl"); A("        pop  de"); A("        pop  bc"); A("        or   a"); A("        ret")
    A("cks_bad:"); A("        pop  hl"); A("        pop  de"); A("        pop  bc"); A("        scf"); A("        ret")
    A("; HL = zero-terminated text, DE = screen address (entry-time only, not timing critical)")
    A("puts:   ld   a,(hl)"); A("        or   a"); A("        ret  z"); A("        or   0x40"); A("        ld   (de),a")
    A("        inc  hl"); A("        inc  de"); A("        jr   puts")
    for lbl,txt in [("s_title","FASTLOAD DEBUG V3"),("s_sync","SYNC LAST:"),("s_end","SYNC END :"),("s_hdr","HDR:"),
                    ("s_body","BODY:"),("s_endad","END:"),("s_cks","CKSUM:"),("s_short","SHORT:"),("s_thr","THR:"),("s_stage","STAGE: .....")]:
        A(f'{lbl}: defm "{txt}"'); A("        defb 0")
    return "\n".join(L)+"\n"

def assemble(org, tag):
    asm=os.path.join(HERE,f"_{tag}.asm"); out=os.path.join(HERE,f"_{tag}.bin")
    open(asm,'w').write(build(org))
    r=subprocess.run(["z80asm","-o",out,asm],capture_output=True,text=True)
    if r.returncode!=0: sys.exit("z80asm failed:\n"+r.stdout+r.stderr)
    b=open(out,'rb').read(); os.remove(asm); os.remove(out); return b

b1=assemble(ORG,"a"); b2=assemble(ORG2,"b")
assert len(b1)==len(b2)
delta=ORG2-ORG; sites=[]; i=0
while i<len(b1):
    if b1[i]!=b2[i]:
        w1=b1[i]|b1[i+1]<<8; w2=b2[i]|b2[i+1]<<8
        assert (w2-w1)&0xFFFF==delta, f"unexplained difference at offset {i}"
        sites.append(i); i+=2
    else: i+=1
open(os.path.join(HERE,"fast_debug_stub.asm"),'w').write(build(ORG))
open(os.path.join(HERE,"fast_debug_stub.bin"),'wb').write(b1)
rows=["    "+", ".join("0x%02X"%x for x in b1[j:j+12])+"," for j in range(0,len(b1),12)]; rows[-1]=rows[-1].rstrip(',')
inc=f"#define FAST_DEBUG_STUB_BASE        0x{ORG:04X}u\nstatic const uint8_t FAST_DEBUG_STUB[{len(b1)}] = {{\n"+"\n".join(rows)+"\n};\n"
inc+=f"\n/* Offsets of 16-bit absolute words that move with the load address (found by assembling at two origins). */\nstatic const uint16_t FAST_DEBUG_RELOCS[{len(sites)}] = {{\n"
inc+="\n".join("    "+", ".join(str(s) for s in sites[j:j+12])+("," if j+12<len(sites) else "") for j in range(0,len(sites),12))+"\n};\n"
open(os.path.join(HERE,"fast_debug_stub.inc"),'w').write(inc)
print(f"image {len(b1)} bytes at 0x{ORG:04X}; {len(sites)} relocation sites")
